/** Bundle the reviewed HiFiSync drawing components into a local Studio module. */
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

if (process.argv.length !== 3) throw Error('Usage: node tools/build_hifisync_drawings.mjs <HiFiSync checkout>');
const root = resolve(process.argv[2]);
const web = join(root, 'packages/web');
const revision = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (execFileSync('git', ['-C', root, 'status', '--porcelain', '--', 'packages/web/app', 'packages/web/messages'], { encoding: 'utf8' }).trim()) {
  throw Error('Commit the HiFiSync drawing sources before building');
}
const dependency = createRequire(join(web, 'package.json'));
const esbuild = createRequire(dependency.resolve('tsx'))('esbuild');
const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, 'hifisync_drawings.tsx'), 'utf8');
const english = JSON.parse(readFileSync(join(web, 'messages/en.json'), 'utf8')).catalog.common.scorecard.roomIso;
const messages = Object.fromEntries(['en', 'de', 'pl'].map(locale => {
  const catalog = JSON.parse(readFileSync(join(web, 'messages', locale + '.json'), 'utf8'));
  const room = {...english, ...catalog.catalog?.common?.scorecard?.roomIso};
  room.views = {
    'front-left': {en:'Isometric',de:'Isometrie',pl:'Izometria'}[locale],
    'front-right': {en:'From the right',de:'Ansicht von rechts',pl:'Widok z prawej'}[locale],
    plan: {en:'Top view',de:'Draufsicht',pl:'Rzut z góry'}[locale],
  };
  return [locale, room];
}));
const result = await esbuild.build({
  absWorkingDir: web, stdin: { contents: source, loader: 'tsx', resolveDir: web, sourcefile: 'hifisync_drawings.tsx' },
  tsconfig: join(web, 'tsconfig.json'), outfile: 'drawings.js', write: false, jsx: 'automatic',
  bundle: true, minify: true, format: 'iife', globalName: 'HiFiSyncDrawings', legalComments: 'inline',
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [{
    name: 'studio-room-translations',
    setup(build) {
      build.onResolve({ filter: /^next-intl$/ }, () => ({ path: 'room-messages', namespace: 'studio' }));
      build.onLoad({ filter: /.*/, namespace: 'studio' }, () => ({ resolveDir: web, contents: `
import {createContext,useContext} from 'react';
export const DrawingLocale = createContext('en');
const messages = ${JSON.stringify(messages)};
export const useTranslations = () => {
 const locale = useContext(DrawingLocale);
 return (key, values = {}) => {
 const parts = key.split('.');
 const message = parts.reduce((value, part) => value?.[part], messages[locale] || messages.en);
 return (message || key).replace(/\\{(\\w+)\\}/g, (_, name) => String(values[name] ?? ''));
 };
};
` }));
      build.onLoad({ filter: /scorecard\.css$/ }, () => ({ contents: '' }));
    },
  }],
});
const js = result.outputFiles.find(file => file.path.endsWith('.js')).text;
const banner = `// Generated by tools/build_hifisync_drawings.mjs from HiFiSync ${revision}.\n`;
writeFileSync(join(here, '../packages/frame-studio/hifisync-drawings.js'), banner + js +
  '\nconst { mountHiFiDrawing } = HiFiSyncDrawings;\nexport { mountHiFiDrawing };\n');
console.log('Pinned HiFiSync drawing sources at ' + revision);
